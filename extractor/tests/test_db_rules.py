@pytest.fixture()
def extracted(tmp_path):
    xml_path = tmp_path / "HR_CS.xml"
    xml_path.write_text(_XML, encoding="utf-8")
    data.run(load_oml_xml(xml_path), tmp_path / "pkg")
    out = tmp_path / "pkg" / "data"

    def load(name):
        return json.loads((out / name).read_text(encoding="utf-8"))

    return {
        "module": "HR_CS",
        "entities": load("entities.json"),
        "relationships": load("relationships.json"),
        "static_data": [],
    }


def _entity(md, name):
    return next(e for e in md["entities"] if e["name"] == name)


def test_worker_reads_delete_rules_indexes_and_flags(extracted):
    emp = _entity(extracted, "Employee")
    rules = {a["name"]: a["delete_rule"] for a in emp["attributes"]}
    assert rules["DepartmentId"] == "Protect"  # attribute omitted -> default
    assert rules["ManagerId"] == "Delete"
    assert rules["DeskId"] == "Ignore"
    assert rules["Code"] is None
    assert emp["is_multitenant"] is True
    assert _entity(extracted, "LocalSetting")["is_client_entity"] is True
    assert emp["indexes"] == [
        {"name": "AutoIndex_DepartmentId", "unique": False, "auto_generated": True,
         "attributes": ["DepartmentId"]},
        {"name": "UX_DepCode", "unique": True, "auto_generated": False,
         "attributes": ["DepartmentId", "Code"]},
    ]


def test_self_reference_is_a_relationship_but_own_id_is_not(extracted):
    rels = {(r["from_entity"], r["from_attribute"]): r for r in extracted["relationships"]}
    assert rels[("Employee", "ManagerId")]["to_entity"] == "Employee"
    assert rels[("Employee", "ManagerId")]["delete_rule"] == "Delete"
    assert ("Employee", "Id") not in rels


def test_ddl_maps_delete_rules_indexes_and_sizes(extracted):
    sql = generate_schema_sql([split_client_entities(extracted)])
    assert "REFERENCES hr_cs__department (id) ON DELETE RESTRICT;" in sql
    assert "REFERENCES hr_cs__employee (id) ON DELETE CASCADE;" in sql
    assert "desk_id" in sql and "REFERENCES hr_cs__desk" not in sql
    assert "delete rule Ignore: no constraint" in sql
    assert "code VARCHAR(20)" in sql
    assert "salary NUMERIC(10,2)" in sql
    assert "CREATE INDEX ix_hr_cs__employee__department_id ON hr_cs__employee (department_id);" in sql
    assert ("CREATE UNIQUE INDEX ux_hr_cs__employee__department_id_code "
            "ON hr_cs__employee (department_id, code);") in sql
    assert "local_setting" not in sql


def test_ddl_with_citext_parses(extracted):
    pglast = pytest.importorskip("pglast")
    sql = generate_schema_sql([split_client_entities(extracted)], ci_text=True)
    assert "CREATE EXTENSION IF NOT EXISTS citext;" in sql
    assert "code CITEXT CHECK (char_length(code) <= 20)" in sql
    pglast.parse_sql(sql)
    pglast.parse_sql(generate_schema_sql([split_client_entities(extracted)]))


def test_column_type_limits():
    text = {"kind": "primitive", "name": "Text"}
    assert column_type({"type": text, "length": 2000}) == "VARCHAR(2000)"
    assert column_type({"type": text, "length": 2001}) == "TEXT"
    assert column_type({"type": text, "length": None}) == "TEXT"
    dec = {"kind": "primitive", "name": "Decimal"}
    assert column_type({"type": dec, "length": "37", "decimals": None}) == "NUMERIC(37,8)"
    assert column_type({"type": dec}) == "NUMERIC"


def test_fk_to_other_module_in_package_is_enforced():
    a = {
        "module": "App_CS",
        "entities": [{"name": "Order", "attributes": [
            {"name": "Id", "type": {"kind": "primitive", "name": "Integer"}, "auto_number": True},
            {"name": "CustomerId", "type": {"kind": "entity_identifier"}},
        ]}],
        "relationships": [{"from_entity": "Order", "from_attribute": "CustomerId",
                           "to_entity": "Customer", "reference_module": "Core_CS",
                           "delete_rule": "Protect"}],
        "static_data": [],
    }
    b = {
        "module": "Core_CS",
        "entities": [{"name": "Customer", "attributes": [
            {"name": "Id", "type": {"kind": "primitive", "name": "Integer"}, "auto_number": True},
        ]}],
        "relationships": [],
        "static_data": [],
    }
    sql = generate_schema_sql([a, b])
    assert "REFERENCES core_cs__customer (id) ON DELETE RESTRICT;" in sql
    assert "constraint in schema.sql" in generate_cross_module_fks([a, b])


def test_seed_moves_identity_sequence_past_explicit_ids():
    md = {
        "module": "App_CS",
        "entities": [{"name": "Status", "attributes": [
            {"name": "Id", "type": {"kind": "primitive", "name": "Integer"}, "auto_number": True},
            {"name": "Label", "type": {"kind": "primitive", "name": "Text"}},
        ]}],
        "relationships": [],
        "static_data": [{"entity_name": "Status", "records": [
            {"values": {"Id": 1, "Label": "Open"}},
            {"values": {"Id": 2, "Label": "Closed"}},
        ]}],
    }
    seed = generate_seed_sql([md])
    assert ("SELECT setval(pg_get_serial_sequence('app_cs__status', 'id'), "
            "(SELECT MAX(id) FROM app_cs__status));") in seed
    pglast = pytest.importorskip("pglast")
    pglast.parse_sql(seed)
